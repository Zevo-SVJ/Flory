// Embeds migrations/*.sql into src/lib/migrations-bundled.ts so serverless runtimes (no reliable filesystem) can migrate.
import fs from "node:fs";
import path from "node:path";
const dir = path.resolve("migrations");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(path.join(dir, f), "utf8"))} },`).join("\n");
fs.writeFileSync("src/lib/migrations-bundled.ts", `// GENERATED by scripts/bundle-migrations.mjs from migrations/*.sql. Do not edit.\nexport const BUNDLED_MIGRATIONS: Array<{ name: string; sql: string }> = [\n${body}\n];\n`);
console.log(`bundled ${files.length} migration(s)`);
